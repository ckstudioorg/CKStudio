/**
 * Blog articles. Each article has two parts:
 * - its card in the `articles` list below: title, summary, category, tags, dates, author, image, service and
 *   reading time. The blog page, service pages, related articles and the search details use only these cards;
 * - its text in its own file, src/content/articles/<slug>.ts: quick answer, key points, body, FAQs and sources.
 *   Each text file is built as its own small download and loaded only on that article's page (lib/loadArticle.ts).
 *
 * To add an article: add its card at the top of `articles` (newest first), copy any file in src/content/articles/
 * to `<new slug>.ts` and write the text. `minutes` is the reading time (words ÷ 220, rounded); `npm test` names
 * the right number if it is off. Then run `npm run share-images` for its link-preview image and cover illustration.
 *
 * The text is a list of blocks: paragraphs, headings, lists, numbered steps, tables, tip boxes and pull quotes.
 * Writing for Google and AI answer engines (ChatGPT, Gemini, Perplexity, Google AI Overviews):
 * - `answer`: 2–3 sentences that directly answer the question in the title (shown as "Quick answer").
 * - `keyPoints`: 3–5 short takeaways. Question-style h2 headings. Tables for comparisons, steps for processes.
 * - `faqs`: real questions people ask, answered in 2–4 sentences (also sent to Google as FAQ data).
 * - `sources`: links for any rule, number or spec that can change. Never invent statistics or client results.
 * - Inside any text: [link text](/services/vfx-and-cg/) makes a link; **words** makes them bold.
 * Optional `image` on the card: a 1200x800 webp in public/images/blog/[slug].webp. Without it, the article's gold line-drawing
 * cover is shown (public/images/blog/covers/<slug>.webp, made by `npm run share-images`).
 */

export type Block =
    | { type: 'p'; text: string }
    | { type: 'h2'; text: string }
    | { type: 'h3'; text: string }
    | { type: 'list'; items: string[] }
    | { type: 'steps'; items: string[] }
    | { type: 'table'; head: string[]; rows: string[][]; caption?: string }
    | { type: 'tip'; text: string }
    | { type: 'quote'; text: string };

/** An article's card: everything lists, links and search details need, without the article's text. */
export interface ArticleMeta {
    slug: string;
    title: string;
    excerpt: string;
    category: string;
    tags: string[];
    date: string; // ISO date, e.g. '2026-10-21'
    updated?: string; // ISO date of the last real update
    author: string;
    image?: string;
    /** Service page slug this article leads to (content/servicePages.ts) */
    service?: string;
    /** Reading time in minutes (words ÷ 220, rounded). A test checks it against the article's text. */
    minutes: number;
}

/** An article's text, kept in its own file: src/content/articles/<slug>.ts */
export interface ArticleContent {
    /** Direct 2–3 sentence answer to the title's question, shown first */
    answer?: string;
    keyPoints?: string[];
    body: Block[];
    faqs?: { q: string; a: string }[];
    sources?: { label: string; url: string }[];
}

/** A whole article: its card plus its text (put together by lib/loadArticle.ts) */
export type Article = ArticleMeta & ArticleContent;

/** Text without link/bold markup, for reading time, search data and the blog search box. */
export const plainText = (text: string) => text.replace(/\[([^\]]+)\]\([^)\s]+\)/g, '$1').replace(/\*\*([^*]+)\*\*/g, '$1');

export const blockText = (b: Block): string => {
    switch (b.type) {
        case 'list':
        case 'steps':
            return b.items.map(plainText).join(' ');
        case 'table':
            return [...b.head, ...b.rows.flat()].map(plainText).join(' ');
        default:
            return plainText(b.text);
    }
};

/** All readable words of an article (quick answer, body and FAQs). */
export const articleText = (a: ArticleContent) =>
    [a.answer ?? '', ...a.body.map(blockText), ...(a.faqs ?? []).flatMap((f) => [f.q, plainText(f.a)])].join(' ');

/** Reading time from the word count (about 220 words a minute): the `minutes` on each card. */
export const readingMinutes = (a: ArticleContent) => Math.max(1, Math.round(articleText(a).split(/\s+/).length / 220));

/** Cover illustration of an article without its own photo (made by scripts/cover-images.mjs; a test checks each exists) */
export const coverImage = (slug: string) => `/images/blog/covers/${slug}.webp`;

/** Reading time as shown on cards and article pages */
export const readTime = (a: ArticleMeta) => `${a.minutes} min read`;

/** Address-friendly id for a heading, for "In this guide" links: "What Is a DCP?" → "what-is-a-dcp" */
export const headingId = (text: string) =>
    plainText(text).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60).replace(/-+$/, '');

